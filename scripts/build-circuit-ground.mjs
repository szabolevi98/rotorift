import * as THREE from 'three';
import clipping from 'polygon-clipping';
import {writeFile} from 'node:fs/promises';
import {buildCircuit} from '../web/game/circuit.js';

const scene=new THREE.Scene(),site=buildCircuit(scene,null,null,{size:800},{authorGround:true});
const layers=new Map(),matrix=new THREE.Matrix4(),p=new THREE.Vector3(),color=new THREE.Color();
const close=points=>[...points,points[0]];
function add(points,y,hex) {
  const key=Math.round(y*100000)+':'+hex;
  if(!layers.has(key))layers.set(key,{y,color:hex,polygons:[]});
  layers.get(key).polygons.push([close(points)]);
}
for(const mesh of site.root.children) {
  if(mesh.userData.groundSurface && mesh.isInstancedMesh) {
    for(let i=0;i<mesh.count;i++) {
      mesh.getMatrixAt(i,matrix);
      const points=[[-.5,-.5],[.5,-.5],[.5,.5],[-.5,.5]].map(([x,z])=>{
        p.set(x,.5,z).applyMatrix4(matrix);return[p.x,p.z];
      });
      add(points,p.y,mesh.material.color.getHex());
    }
  } else if(mesh.isMesh && !mesh.isInstancedMesh && mesh.geometry.attributes.normal?.getY(0)>.99) {
    if(mesh.name==='Apex_grass_landscape')continue;
    const g=mesh.geometry.index?mesh.geometry.toNonIndexed():mesh.geometry,positions=g.attributes.position,colors=g.attributes.color;
    for(let i=0;i<positions.count;i+=3) {
      const points=[0,1,2].map(j=>[positions.getX(i+j),positions.getZ(i+j)]);
      if(Math.abs((points[1][0]-points[0][0])*(points[2][1]-points[0][1])-(points[1][1]-points[0][1])*(points[2][0]-points[0][0]))<1e-10)continue;
      if(colors)color.fromBufferAttribute(colors,i);else color.copy(mesh.material.color);
      add(points,positions.getY(i),color.getHex());
    }
    if(g!==mesh.geometry)g.dispose();
  }
}
add([[-400,-400],[400,-400],[400,400],[-400,400]],-.05,0x647e43);
let mask=[];const result=[];
for(const layer of [...layers.values()].sort((a,b)=>b.y-a.y)) {
  const united=clipping.union(...layer.polygons),visible=mask.length?clipping.difference(united,mask):united;
  mask=mask.length?clipping.union(mask,united):united;
  const polygons=[];
  // Tile before triangulation: a large grass region must not become another
  // giant triangle spanning the camera near plane at high altitude.
  const entries=visible.map(polygon=>{
    const xs=polygon[0].map(p=>p[0]),zs=polygon[0].map(p=>p[1]);
    return {polygon,minX:Math.min(...xs),maxX:Math.max(...xs),minZ:Math.min(...zs),maxZ:Math.max(...zs)};
  });
  for(let x=-400;x<400;x+=25)for(let z=-400;z<400;z+=25) {
    const candidates=entries.filter(p=>p.maxX>x&&p.minX<x+25&&p.maxZ>z&&p.minZ<z+25);
    if(!candidates.length)continue;
    const tile=[close([[x,z],[x+25,z],[x+25,z+25],[x,z+25]])];
    polygons.push(...clipping.intersection(candidates.map(p=>p.polygon),tile));
  }
  if(polygons.length)result.push({color:layer.color,y:Math.round(layer.y*100000)/100000,polygons});
}
await writeFile(new URL('../shared/world/circuit-ground-data.js',import.meta.url),
  '// Generated by node scripts/build-circuit-ground.mjs. Non-overlapping tiled ground.\nexport const CIRCUIT_GROUND = '+JSON.stringify(result)+';\n');
site.dispose();console.log('Apex ground:',result.length,'disjoint color/height layers');

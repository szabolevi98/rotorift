import polygonClipping from 'polygon-clipping';
import {writeFile} from 'node:fs/promises';
import {CIRCUIT_SAMPLES} from '../shared/world/circuit-layout.js';
import {pitEdge} from '../shared/world/circuit-pits.js';

// Authoring-time boolean operations keep runtime geometry dependency-free.
// The pit entries are one asphalt surface, cut against the actual circuit edge.
const close = points => [...points, points[0]];
const rectangle = (x,z,width,depth,yaw=0) => [close(
  [[-1,-1],[1,-1],[1,1],[-1,1]].map(([sx,sz])=>{
    const dx=sx*width/2,dz=sz*depth/2;
    return [x+dx*Math.cos(yaw)+dz*Math.sin(yaw),z-dx*Math.sin(yaw)+dz*Math.cos(yaw)];
  }),
)];
const rims = [-9,9].map(offset => close(CIRCUIT_SAMPLES.map(s=>[s.x-s.tz*offset,s.z+s.tx*offset])));
const area = points => Math.abs(points.reduce((a,p,i)=>{
  const q=points[(i+1)%points.length];return a+p[0]*q[1]-q[0]*p[1];
},0));
rims.sort((a,b)=>area(b)-area(a));
const lane = [close([...pitEdge(-7),...pitEdge(7).reverse()])];
const joined = polygonClipping.union(lane,rectangle(0,187,224,18));
const apron = polygonClipping.difference(joined,rims);
await writeFile(new URL('../shared/world/circuit-apron.js',import.meta.url),
  '// Generated by node scripts/build-circuit-apron.mjs. Disjoint from the circuit strips.\n'+
  'export const CIRCUIT_PIT_APRON = '+JSON.stringify(apron)+';\n');

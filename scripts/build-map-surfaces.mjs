import clipping from 'polygon-clipping';
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { PARK_PATHS, PARK_PATH_SAMPLES, PARK_BENCHES, PARK_GARDEN, sampleParkPath } from '../shared/world/park-layout.js';
import { CONSTRUCTION_ROADS, CONSTRUCTION_YARDS } from '../shared/world/construction-layout.js';

const snap = n => Math.round(n * 1000) / 1000;
function rectangle(x, z, width, depth) {
  return [[[x-width/2,z-depth/2],[x+width/2,z-depth/2],[x+width/2,z+depth/2],[x-width/2,z+depth/2],[x-width/2,z-depth/2]]];
}
function stroke(points, width) {
  const samples = sampleParkPath(points);
  const edges = samples.map(p => [-1,1].map(side => [snap(p.x-p.tz*side*width/2),snap(p.z+p.tx*side*width/2)]));
  return edges.slice(1).map((edge,i) => [[edges[i][0],edges[i][1],edge[1],edge[0],edges[i][0]]]);
}
function tileSurfaces(polygons, half) {
  // Local polygons prevent triangulation of a long curved network into fans
  // spanning the entire park. The browser only tessellates small surface tiles.
  const entries = polygons.map(polygon => {
    const xs=polygon[0].map(p=>p[0]), zs=polygon[0].map(p=>p[1]);
    return {polygon,minX:Math.min(...xs),maxX:Math.max(...xs),minZ:Math.min(...zs),maxZ:Math.max(...zs)};
  });
  const result=[],size=16;
  for(let x=Math.floor(-half/size)*size;x<half;x+=size) for(let z=Math.floor(-half/size)*size;z<half;z+=size) {
    const candidates=entries.filter(p=>p.maxX>x && p.minX<x+size && p.maxZ>z && p.minZ<z+size);
    if(candidates.length) result.push(...clipping.intersection(candidates.map(p=>p.polygon),rectangle(x+size/2,z+size/2,size,size)));
  }
  return result;
}
export function surfaceSourceHash() {
  const hash = createHash('sha256');
  for (const path of ['../shared/world/park-layout.js','../shared/world/construction-layout.js','./build-map-surfaces.mjs'])
    hash.update(readFileSync(new URL(path, import.meta.url), 'utf8').replace(/\r\n/g, '\n'));
  return hash.digest('hex');
}
export function calculateMapSurfaces() {
  const paved = clipping.union(...PARK_PATHS.filter(p=>p.paving).flatMap(p=>stroke(p.points,p.width)));
  const extras = [rectangle(PARK_GARDEN.x,PARK_GARDEN.z,PARK_GARDEN.width,PARK_GARDEN.depth)];
  const pathPoints = PARK_PATH_SAMPLES.flat();
  for (const seat of PARK_BENCHES) {
    extras.push(...stroke([[seat.x-seat.tx*1.9,seat.z-seat.tz*1.9],[seat.x+seat.tx*1.9,seat.z+seat.tz*1.9]],2.8));
    // A short footpath connects each seating bay instead of leaving a grass gap.
    const normal = [-seat.tz,seat.tx];
    const nearest = pathPoints.reduce((best,p) => Math.hypot(p.x-seat.x,p.z-seat.z)<Math.hypot(best.x-seat.x,best.z-seat.z)?p:best);
    extras.push(...stroke([[nearest.x,nearest.z],[seat.x-normal[0]*Math.sign((seat.x-nearest.x)*normal[0]+(seat.z-nearest.z)*normal[1])*1.3,seat.z-normal[1]*Math.sign((seat.x-nearest.x)*normal[0]+(seat.z-nearest.z)*normal[1])*1.3]],1.2));
  }
  const bounds = rectangle(0,0,700,700);
  const all = clipping.intersection(clipping.union(paved,...extras,...PARK_PATHS.filter(p=>!p.paving).flatMap(p=>stroke(p.points,p.width))),bounds);
  const border = clipping.union(...PARK_PATHS.filter(p=>p.width>=4).flatMap(p=>stroke(p.points,p.width+0.32)));
  const surfaces = {
    parkPaving: clipping.intersection(paved,bounds),
    parkGravel: clipping.difference(all,paved),
    parkCurbs: clipping.intersection(clipping.difference(border,all),bounds),
    constructionRoads: clipping.intersection(clipping.union(...[...CONSTRUCTION_ROADS,...CONSTRUCTION_YARDS].map(p=>rectangle(p.x,p.z,p.width,p.depth))),rectangle(0,0,600,600)),
  };
  return Object.fromEntries(Object.entries(surfaces).map(([name,polygons])=>[name,tileSurfaces(polygons,name==='constructionRoads'?300:350)]));
}
export function buildMapSurfaces() {
  const output = '// Generated by npm run maps:build. Polygon booleans run at build time only.\n'
    + `export const surfaceSourceHash = ${JSON.stringify(surfaceSourceHash())};\n`
    + Object.entries(calculateMapSurfaces()).map(([name,rings])=>`export const ${name} = ${JSON.stringify(rings)};`).join('\n')+'\n';
  writeFileSync(fileURLToPath(new URL('../shared/world/map-surfaces.js',import.meta.url)),output);
}
if (process.argv[1] && import.meta.url===pathToFileURL(process.argv[1]).href) buildMapSurfaces();
